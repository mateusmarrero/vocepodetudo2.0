const { execSync } = require('child_process');
const output = execSync('php "C:\\Users\\usuario\\Downloads\\VCPDTD ANTIGRAVITY\\sitemap.php"', { encoding: 'utf8' });
const locMatches = output.match(/<loc>(.*?)<\/loc>/g) || [];
console.log('Total URLs generated by sitemap.php:', locMatches.length);
const blogMatches = locMatches.filter(u => u.includes('/artigo/'));
console.log('Blog article URLs in sitemap.php:', blogMatches.length);
const staticMatches = locMatches.filter(u => !u.includes('/artigo/'));
console.log('Static URLs in sitemap.php:', staticMatches.length);
